#!/usr/bin/env python3
"""sasrt-nx (2026-11-11, machine-copy idea 46, part 2): the stable globals of a census log (sasrt_cpu_frozen_census,
app/src/cpu/banjo_hot_guest.cpp) into app/src/cpu/hot/frozen.txt, which tools/localize_native.py reads (FROZEN).

A global is taken when it never changed during the census, or last changed before --settled seconds (the loading
before the race: the census starts with the first hook). Each line: `<address> <size> <value>` in hex, with a comment
saying where the value came from. Only integer sizes (1, 2, 4, 8 bytes).

  python tools/frozen_pick.py --log out/console_runs/b2census/sasrt_NNN.log [--settled 100]
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'app', 'src', 'cpu', 'hot', 'frozen.txt')
LINE = re.compile(r'\[frozen\] (0x[0-9a-f]+) size (\d+) value (0x[0-9a-f]+) \(first (0x[0-9a-f]+)\): (\d+) changes, '
                  r'the last at ([0-9.]+) s')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--log', required=True)
    ap.add_argument('--settled', type=float, default=100.0)
    a = ap.parse_args()
    rows = []
    for line in open(a.log, encoding='utf-8', errors='replace'):
        m = LINE.search(line)
        if not m:
            continue
        addr, size, value = int(m.group(1), 16), int(m.group(2)), int(m.group(3), 16)
        changes, last = int(m.group(5)), float(m.group(6))
        if size in (1, 2, 4, 8) and (changes == 0 or last < a.settled):
            rows.append((addr, size, value))
    if not rows:
        sys.exit('frozen_pick: no census lines in %s' % a.log)
    head = ('# GENERATED by tools/frozen_pick.py (machine-copy idea 46, part 2) from %s: the writable guest globals the\n'
            '# copies load at a known address that did not change after %.0f s of the census (sasrt_cpu_frozen_census).\n'
            '# tools/localize_native.py builds their values into the copies\' loops behind an entry check. Edit freely:\n'
            '# a line is "<address> <size> <value>" (hex); an empty file freezes nothing.\n'
            % (os.path.relpath(a.log, ROOT).replace(os.sep, '/'), a.settled))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(head + ''.join('%08X %d %X\n' % r for r in sorted(rows)))
    print('frozen_pick: %d globals into %s' % (len(rows), OUT))


if __name__ == '__main__':
    main()
